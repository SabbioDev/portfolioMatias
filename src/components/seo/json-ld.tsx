import { personSchema, websiteSchema } from "@/lib/seo";

export function JsonLd() {
  const schemas = [personSchema(), websiteSchema()];

  return (
    <>
      {schemas.map((schema) => (
        <script
          key={schema["@type"]}
          type="application/ld+json"
          dangerouslySetInnerHTML={{
            __html: JSON.stringify(schema).replace(/</g, "\\u003c"),
          }}
        />
      ))}
    </>
  );
}
